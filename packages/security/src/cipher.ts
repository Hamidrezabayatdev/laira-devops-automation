import crypto from 'node:crypto';

export interface AadContext {
  workspaceId: string;
  connectionId: string;
  version: number | string;
  keyVersion?: number;
}

export interface CredentialEnvelope {
  algorithm: 'aes-256-gcm';
  ciphertext: string; // base64
  iv: string;         // base64
  tag: string;        // base64
  keyVersion: number;
  workspaceId: string;
  connectionId: string;
  version: string;
}

export class CredentialEncryptionError extends Error {
  constructor(message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'CredentialEncryptionError';
  }
}

export class CredentialDecryptionError extends Error {
  constructor(message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'CredentialDecryptionError';
  }
}

/**
 * Deterministically formats the AAD context into a sorted JSON buffer.
 */
export function formatAadContext(context: AadContext): Buffer {
  if (!context.workspaceId || typeof context.workspaceId !== 'string') {
    throw new CredentialEncryptionError('workspaceId must be a non-empty string');
  }
  if (!context.connectionId || typeof context.connectionId !== 'string') {
    throw new CredentialEncryptionError('connectionId must be a non-empty string');
  }
  if (context.version === undefined || context.version === null || String(context.version).trim() === '') {
    throw new CredentialEncryptionError('version must be non-empty');
  }

  const normalized = {
    connectionId: context.connectionId,
    keyVersion: Number(context.keyVersion ?? 1),
    version: String(context.version),
    workspaceId: context.workspaceId,
  };

  return Buffer.from(JSON.stringify(normalized), 'utf8');
}

/**
 * Normalizes a 256-bit (32 bytes) encryption key from Buffer, hex string, base64url, or standard base64.
 */
export function normalizeKey(key: Buffer | string): Buffer {
  let keyBuf: Buffer;
  if (Buffer.isBuffer(key)) {
    keyBuf = key;
  } else if (typeof key === 'string') {
    const trimmed = key.trim();
    if (trimmed.length === 64 && /^[0-9a-fA-F]{64}$/.test(trimmed)) {
      keyBuf = Buffer.from(trimmed, 'hex');
    } else {
      // Try base64url first (supports URL-safe base64 generated by crypto tools)
      const b64urlBuf = Buffer.from(trimmed, 'base64url');
      if (b64urlBuf.length === 32) {
        keyBuf = b64urlBuf;
      } else {
        keyBuf = Buffer.from(trimmed, 'base64');
      }
    }
  } else {
    throw new CredentialEncryptionError('Key must be a Buffer or string');
  }

  if (keyBuf.length !== 32) {
    throw new CredentialEncryptionError(
      `Invalid key length: expected 32 bytes (256 bits), got ${keyBuf.length} bytes`
    );
  }

  return keyBuf;
}

/**
 * Encrypts sensitive credentials using AES-256-GCM with contextual AAD binding.
 * Context must bind workspaceId, connectionId, and version.
 */
export function encryptCredential(
  plaintext: string | Buffer,
  key: Buffer | string,
  context: AadContext,
  keyVersion = 1
): CredentialEnvelope {
  try {
    const effectiveKeyVersion = context.keyVersion ?? keyVersion ?? 1;
    const keyBuf = normalizeKey(key);
    const effectiveContext: AadContext = {
      ...context,
      keyVersion: effectiveKeyVersion,
    };
    const aadBuf = formatAadContext(effectiveContext);
    const iv = crypto.randomBytes(12); // 96-bit IV recommended for GCM

    const cipher = crypto.createCipheriv('aes-256-gcm', keyBuf, iv);
    cipher.setAAD(aadBuf);

    const inputBuf = Buffer.isBuffer(plaintext) ? plaintext : Buffer.from(plaintext, 'utf8');
    const ciphertext = Buffer.concat([cipher.update(inputBuf), cipher.final()]);
    const tag = cipher.getAuthTag();

    return {
      algorithm: 'aes-256-gcm',
      ciphertext: ciphertext.toString('base64'),
      iv: iv.toString('base64'),
      tag: tag.toString('base64'),
      keyVersion: effectiveKeyVersion,
      workspaceId: context.workspaceId,
      connectionId: context.connectionId,
      version: String(context.version),
    };
  } catch (err) {
    if (err instanceof CredentialEncryptionError) {
      throw err;
    }
    throw new CredentialEncryptionError(
      `Credential encryption failed: ${err instanceof Error ? err.message : String(err)}`,
      { cause: err }
    );
  }
}

/**
 * Decrypts a credential envelope using AES-256-GCM and verifies contextual AAD.
 * Throws CredentialDecryptionError if AAD mismatches or authentication tag fails.
 */
export function decryptCredential(
  envelope: CredentialEnvelope,
  key: Buffer | string,
  expectedContext: AadContext
): Buffer {
  if (!envelope || envelope.algorithm !== 'aes-256-gcm') {
    throw new CredentialDecryptionError('Invalid envelope or unsupported algorithm');
  }

  // Strict contextual AAD check against envelope metadata
  if (envelope.workspaceId !== expectedContext.workspaceId) {
    throw new CredentialDecryptionError(
      `AAD mismatch: workspaceId does not match (expected ${expectedContext.workspaceId}, got ${envelope.workspaceId})`
    );
  }

  if (envelope.connectionId !== expectedContext.connectionId) {
    throw new CredentialDecryptionError(
      `AAD mismatch: connectionId does not match (expected ${expectedContext.connectionId}, got ${envelope.connectionId})`
    );
  }

  if (String(envelope.version) !== String(expectedContext.version)) {
    throw new CredentialDecryptionError(
      `AAD mismatch: version does not match (expected ${expectedContext.version}, got ${envelope.version})`
    );
  }

  if (expectedContext.keyVersion !== undefined && expectedContext.keyVersion !== envelope.keyVersion) {
    throw new CredentialDecryptionError(
      `AAD mismatch: keyVersion does not match (expected ${expectedContext.keyVersion}, got ${envelope.keyVersion})`
    );
  }

  let keyBuf: Buffer;
  try {
    keyBuf = normalizeKey(key);
  } catch (err) {
    throw new CredentialDecryptionError(
      `Invalid decryption key: ${err instanceof Error ? err.message : String(err)}`,
      { cause: err }
    );
  }

  let ivBuf: Buffer;
  let tagBuf: Buffer;
  let ciphertextBuf: Buffer;

  try {
    ivBuf = Buffer.from(envelope.iv, 'base64');
    tagBuf = Buffer.from(envelope.tag, 'base64');
    ciphertextBuf = Buffer.from(envelope.ciphertext, 'base64');

    if (ivBuf.length !== 12) {
      throw new Error(`Invalid IV length: expected 12 bytes, got ${ivBuf.length}`);
    }
    if (tagBuf.length !== 16) {
      throw new Error(`Invalid tag length: expected 16 bytes, got ${tagBuf.length}`);
    }
  } catch (err) {
    throw new CredentialDecryptionError(
      `Malformed envelope payload: ${err instanceof Error ? err.message : String(err)}`,
      { cause: err }
    );
  }

  // Bind envelope.keyVersion into the AAD buffer so any tampering with keyVersion fails authentication
  const effectiveExpectedContext: AadContext = {
    ...expectedContext,
    keyVersion: expectedContext.keyVersion ?? envelope.keyVersion ?? 1,
  };

  const aadBuf = formatAadContext(effectiveExpectedContext);

  try {
    const decipher = crypto.createDecipheriv('aes-256-gcm', keyBuf, ivBuf);
    decipher.setAAD(aadBuf);
    decipher.setAuthTag(tagBuf);

    const decrypted = Buffer.concat([decipher.update(ciphertextBuf), decipher.final()]);
    return decrypted;
  } catch (err) {
    throw new CredentialDecryptionError(
      'Authentication tag verification failed or ciphertext tampered',
      { cause: err }
    );
  }
}
